// Checking a reader's suggestion (#48): the arithmetic of the review step.
//
// A signed-in reader's "Add a place" waits in `reader_place_suggestions`, seen by nobody but
// its author. A moderator looks at it and either rejects it, with a reason the reader can
// read, or verifies it: it then enters `location_submissions` as a 'reader' row, status
// 'verified', and the map draws it as a checked candidate. The writing is in
// `app/api/review/suggestions/route.js`; this module decides who may, and what is written.
//
// **Who is a moderator.** A signed-in account whose email is listed in MODERATOR_EMAILS.
// Fail closed: no list, nobody, so a rebuilt environment shuts the door instead of opening it.

export const REVIEW_ACTIONS = Object.freeze({ verify: "verify", reject: "reject" });

const MAX_REASON = 300;
const MAX_SENTENCE = 600;
const UUID = /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i;

export function moderatorEmails(env = process.env) {
  return String(env?.MODERATOR_EMAILS ?? "")
    .split(/[\s,;]+/)
    .map((entry) => entry.trim().toLowerCase())
    .filter((entry) => entry.includes("@"));
}

// Only an email the provider confirmed counts: an unconfirmed address is a string anybody
// could have typed into a sign-up form.
export function isModerator(user, env = process.env) {
  const email = String(user?.email ?? "").trim().toLowerCase();
  if (!email || !user?.id) return false;
  if (!user.email_confirmed_at && !user.confirmed_at) return false;
  return moderatorEmails(env).includes(email);
}

function cleanUrl(value) {
  const raw = String(value ?? "").trim();
  if (!raw) return null;
  try {
    const url = new URL(raw);
    return /^https?:$/.test(url.protocol) && raw.length <= 2000 ? url.toString() : null;
  } catch {
    return null;
  }
}

// Returns { decision } or { error }. A verdict is checked before anything is read or written.
export function parseReviewDecision(body) {
  const id = String(body?.id ?? "").trim();
  if (!UUID.test(id)) return { error: "Name the suggestion to review." };

  const action = String(body?.action ?? "");
  const reason = String(body?.reason ?? "").trim().slice(0, MAX_REASON);

  if (action === REVIEW_ACTIONS.reject) {
    // The reader reads this, so a rejection says why.
    if (reason.length < 3) return { error: "Say why it is not accepted; the reader will see it." };
    return { decision: { id, action, reason } };
  }

  if (action === REVIEW_ACTIONS.verify) {
    const workId = String(body?.workId ?? "").trim();
    if (!UUID.test(workId)) return { error: "Choose the work this place belongs to." };
    // Every stored fact says where it came from (2026-08-05): no link, no verification.
    const sourceUrl = cleanUrl(body?.sourceUrl);
    if (!sourceUrl) return { error: "Give the web page that backs the claim." };
    return { decision: { id, action, reason, workId, sourceUrl } };
  }

  return { error: "Choose verify or reject." };
}

// The sentence the card prints for a checked suggestion. It says whose claim it is.
export function readerSentence(suggestion, workTitle) {
  const place = String(suggestion?.place_name ?? "").trim();
  const work = String(workTitle ?? suggestion?.work_title ?? "").trim();
  const scene = String(suggestion?.scene ?? "").trim();
  const sentence = scene
    ? `A reader placed ${work} at ${place}: ${scene}`
    : `A reader placed ${work} at ${place}.`;
  return sentence.slice(0, MAX_SENTENCE);
}

function hostOf(url) {
  try {
    return new URL(url).hostname.replace(/^www\./, "");
  } catch {
    return "";
  }
}

// The queue row a verified suggestion becomes. `place_key` is generated by the database.
export function submissionFromSuggestion(suggestion, { workId, workTitle, sourceUrl, reason }) {
  const host = hostOf(sourceUrl);
  return {
    work_id: workId,
    place_name: String(suggestion.place_name).trim(),
    source_kind: "reader",
    source_record_id: suggestion.id,
    source_sentence: readerSentence(suggestion, workTitle),
    source_title: host ? `A reader's suggestion, checked against ${host}` : "A reader's suggestion",
    source_url: sourceUrl,
    source_license: "Reader contribution",
    lat: suggestion.lat,
    lng: suggestion.lng,
    // The point is where the reader put it on the map; the moderator checked the place,
    // nobody measured the coordinate.
    geocode_source: "reader",
    geocode_license: "Reader contribution",
    geocode_reason: "placed on the map by the reader, checked by a moderator",
    status: "verified",
    status_reason: reason ? `checked by a moderator: ${reason}` : "checked by a moderator",
    reviewed_at: new Date().toISOString(),
  };
}

// What the suggestion row says after the verdict.
export function suggestionAfterReview(decision, { moderatorId, submissionId = null, now = new Date() }) {
  const verified = decision.action === REVIEW_ACTIONS.verify;
  return {
    status: verified ? "verified" : "rejected",
    status_reason: decision.reason || (verified ? "checked by a moderator" : null),
    reviewed_at: now.toISOString(),
    reviewed_by: moderatorId,
    submission_id: verified ? submissionId : null,
  };
}

// What the reader's own list shows once a suggestion has been looked at.
export function reviewOutcomeLabel(row) {
  if (row?.status === "verified") return "Checked · it is on the map";
  if (row?.status === "rejected") {
    const reason = String(row?.status_reason ?? "").trim();
    return reason ? `Not accepted · ${reason}` : "Not accepted";
  }
  return null;
}

// The reader's own reviewed suggestions, by the id their browser gave each one. Read under
// the reader's session, so row-level security returns only their rows. Never throws: no
// answer means the list keeps saying "sent for review".
export async function readReviewOutcomes(client) {
  const outcomes = new Map();
  try {
    const { data, error } = await client
      .from("reader_place_suggestions")
      .select("client_id, status, status_reason")
      .neq("status", "pending");
    if (error) return outcomes;
    for (const row of data ?? []) {
      const label = reviewOutcomeLabel(row);
      if (row?.client_id && label) outcomes.set(row.client_id, label);
    }
  } catch {
    // Offline or signed out mid-read: nothing to add.
  }
  return outcomes;
}
